type Translator = (source: string, values?: Record<string, string | number>) => string;
/** Keep stable error sources in state so existing notices follow language changes. */
export function localizeVisualUtilityError(t: Translator, error: string): string {
    const source = error.replace(/^(?:Error: )+/, "");
    const bounds = /^(.*?) must be (-?[\d.]+)–(-?[\d.]+)\.$/.exec(source);
    if (bounds) return t("{field} must be {minimum}–{maximum}.", { field: t(bounds[1]), minimum: bounds[2], maximum: bounds[3] });
    const line = /^Line (\d+) exceeds the image width\. Enable line wrapping, increase width or reduce font size\.$/.exec(source);
    if (line) return t("Line {line} exceeds the image width. Enable line wrapping, increase width or reduce font size.", { line: line[1] });
    return t(source);
}
