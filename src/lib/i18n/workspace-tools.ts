type WorkspaceTranslator = (source: string, values?: Record<string, string | number>) => string;

/** Translate authored workflow context while retaining third-party parser details.
 * This runs at render time so changing language never rewrites saved workflows. */
export function localizeWorkflowDiagnostic(source: string, t: WorkspaceTranslator): string {
    const limit = /^Step (\d+): (data|output) exceeds the 2 MiB limit\.$/.exec(source);
    if (limit) return t(limit[2] === "data" ? "Step {number}: data exceeds the 2 MiB limit." : "Step {number}: output exceeds the 2 MiB limit.", { number: limit[1] });
    const step = /^Step (\d+) \(([^\n]+?)\): ([\s\S]*)$/.exec(source);
    if (step) return t("Step {number} ({operation}): {details}", { number: step[1], operation: t(step[2]), details: t(step[3]) });
    return t(source);
}
