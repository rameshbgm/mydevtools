type Translator = (source: string, values?: Record<string, string | number>) => string;
/** Keep stored diagnostics as sources so changing locale also updates existing notices. */
export function identifierConfigMessage(source: string, t: Translator): string {
    const message = source.replace(/^Error: /, "");
    const patterns: [RegExp, string, string[]][] = [
        [/^Unknown template: ([\s\S]+)$/, "Unknown template: {name}", ["name"]],
        [/^Duplicate environment variable: ([\s\S]+)\.$/, "Duplicate environment variable: {name}.", ["name"]],
        [/^Dependency cycle includes ([\s\S]+)\.$/, "Dependency cycle includes {name}.", ["name"]],
        [/^([\s\S]+): unknown dependency ([\s\S]+)\.$/, "{name}: unknown dependency {dependency}.", ["name", "dependency"]],
        [/^Host port collision: 127\.0\.0\.1:([\s\S]+)\.$/, "Host port collision: 127.0.0.1:{port}.", ["port"]],
        [/^([\s\S]+) is shared by ([\s\S]+)\. Separate database services should not share a data volume\.$/, "{volume} is shared by {names}. Separate database services should not share a data volume.", ["volume", "names"]],
    ];
    for (const [pattern, key, fields] of patterns) {
        const match = pattern.exec(message);
        if (match) return t(key, Object.fromEntries(fields.map((field, index) => [field, match[index + 1]])));
    }
    // Match a known diagnostic suffix; service names can contain punctuation in invalid drafts.
    for (const key of Object.keys(IDENTIFIER_CONFIG_TRANSLATIONS)) {
        if (key.startsWith("{name}: ") && message.endsWith(key.slice(6))) {
            return t(key, { name: message.slice(0, -key.slice(6).length) });
        }
    }
    return t(message);
}
