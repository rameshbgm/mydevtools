type Translator = (source: string, values?: Record<string, string | number>) => string;
/** Stored parser/provider diagnostics stay exact; translate authored framing only. */
export function formatAiDiagnostic(source: string, t: Translator): string {
    const patterns: [RegExp, string, string[]][] = [
        [/^invalid JSON: ([\s\S]*)$/, "Invalid JSON: {detail}", ["detail"]],
        [/^skill\[(\d+)\]: "([^"]+)" is required$/, "Skill {index}: {field} is required", ["index", "field"]],
        [/^message\[(\d+)\]: invalid or missing "role" \(got (.*)\)$/, "Message {index}: invalid or missing role ({detail})", ["index", "detail"]],
        [/^message\[(\d+)\]: invalid or missing "role" \(must be "user" or "assistant", got (.*)\)$/, "Message {index}: expected user/assistant role ({detail})", ["index", "detail"]],
        [/^message\[(\d+)\]: "content" must be a string$/, "Message {index}: content must be a string", ["index"]],
        [/^message\[(\d+)\]: "system" role must be the first message$/, "Message {index}: system must come first", ["index"]],
        [/^message\[(\d+)\]: two consecutive "(.*)" messages — roles should alternate$/, "Message {index}: consecutive {role} messages; roles should alternate", ["index", "role"]],
        [/^message\[(\d+)\]: consecutive messages must alternate user\/assistant$/, "Message {index}: alternate user/assistant roles", ["index"]],
        [/^contents\[(\d+)\]: invalid or missing "role" \(must be "user" or "model", got (.*)\)$/, "Content {index}: expected user/model role ({detail})", ["index", "detail"]],
        [/^contents\[(\d+)\]: "parts" must be a non-empty array$/, "Content {index}: parts must be a non-empty array", ["index"]],
        [/^contents\[(\d+)\]: no part carries a "text" string$/, "Content {index}: no text string in parts", ["index"]],
        [/^contents\[(\d+)\]: consecutive entries must alternate user\/model$/, "Content {index}: alternate user/model roles", ["index"]],
        [/^~(\d+) chars, (\d+) char overlap$/, "About {size} characters, {overlap} overlap", ["size", "overlap"]],
        [/^(\d+) chunk\(s\) from ([\d,]+) chars$/, "{chunks} chunks from {chars} characters", ["chunks", "chars"]],
        [/^running on (.*)$/, "Running on {device}", ["device"]],
        [/^(\d+) × (\d+)-dim vectors \(([\d.]+) ms\/chunk\)$/, "{chunks} × {dimensions}-dimension vectors ({ms} ms/chunk)", ["chunks", "dimensions", "ms"]],
        [/^([\d.]+) KB of float32 held in memory$/, "{size} KB of float32 in memory", ["size"]],
    ];
    for (const [pattern, template, names] of patterns) {
        const match = source.match(pattern);
        if (match) return t(template, Object.fromEntries(names.map((name, index) => [name, match[index + 1]])));
    }
    return t(source);
}
